// Verbia UI strings. Every language must stay symmetric — all of them carry
// the same key set as EN. Brand copy (slogan / UX line) has official
// bilingual versions; UI copy follows the chosen interface language
// (UserSettings.uiLanguage: "auto" follows the browser).

export type UiLang = "en" | "zh-CN" | "es" | "pt-BR" | "ja" | "de" | "fr" | "ko" | "it" | "tr" | "vi" | "id";

const UI_LANGS: readonly UiLang[] = ["en", "zh-CN", "es", "pt-BR", "ja", "de", "fr", "ko", "it", "tr", "vi", "id"];

export function resolveUiLang(pref: string | undefined, browserLocale: string | undefined): UiLang {
  if (pref && (UI_LANGS as readonly string[]).includes(pref)) return pref as UiLang;
  const bl = (browserLocale ?? "").toLowerCase();
  if (bl.startsWith("zh")) return "zh-CN";
  if (bl.startsWith("pt")) return "pt-BR";
  if (bl.startsWith("es")) return "es";
  if (bl.startsWith("ja")) return "ja";
  if (bl.startsWith("de")) return "de";
  if (bl.startsWith("fr")) return "fr";
  if (bl.startsWith("ko")) return "ko";
  if (bl.startsWith("it")) return "it";
  if (bl.startsWith("tr")) return "tr";
  if (bl.startsWith("vi")) return "vi";
  // Indonesian is "id", but older Chrome builds still report the legacy "in".
  if (bl.startsWith("id") || bl.startsWith("in")) return "id";
  return "en";
}

